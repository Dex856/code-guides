def python_prelude(code: str) -> str:
    """The bank snippets rely on the judge's namespace for a few helpers; a real
    interpreter needs the imports written out."""
    needed = []
    for pattern, line in PY_IMPORTS:
        if re.search(pattern, code):
            module = line.split()[1].split(".")[0] if line.startswith("from") else line.split()[1]
            if re.search(r"^\s*(?:from\s+" + module + r"\s+import|import\s+" + module + r"\b)", code, re.M):
                continue
            needed.append(line)
    return "\n".join(needed) + ("\n\n" if needed else "")

NODE_MARKERS = re.compile(r"\b(TreeNode|ListNode|Node|TreeLinkNode)\b")
# APIs the judge provides (declared in a snippet but never defined) — a demo
# program cannot link or run against them, so those problems ship without one.
JUDGE_APIS = re.compile(r"\b(isBadVersion|is_bad_version|guess|MountainArray|read4|Reader4|NestedInteger|ArrayReader|Master|Sea)\b")


def python_demo(code: str, example: str, other_langs: str = "") -> str | None:
    # The example is a serialised tree / linked list / graph when any language's
    # solution mentions a node type — a Python signature alone cannot show that.
    if NODE_MARKERS.search(code) or NODE_MARKERS.search(other_langs) or JUDGE_APIS.search(code):
        return None
    values = parse_example_values(example)
    if not values:
        return None
    src = strip_comments(code, python=True)
    m = re.search(r"^def\s+(\w+)\s*\(([^)]*)\)\s*:", src, re.M)
    if not m:
        return None
    name, params = m.group(1), m.group(2)
    args = []
    for raw in split_top(params):
        arg = raw.strip().split(":")[0].split("=")[0].strip()
        if arg in ("self", "cls") or not arg:
            if arg in ("self", "cls"):
                return None
            continue
        if arg not in values:
            return None
        args.append(repr(values[arg]))
    return (f"_result = {name}({', '.join(args)})\n"
            f"if _result is not None:\n"
            f"    print(_result)")


