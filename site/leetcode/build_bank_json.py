#!/usr/bin/env python3
"""
Build site/leetcode/problems.json — the data behind the practice terminal.

For every problem in every bank this emits the statement, examples, constraints,
approach, complexity and the three language solutions, PLUS (best effort):

  · starter[lang]       a skeleton with the real signature + an entry point
  · solution_run[lang]  a complete, runnable program: solution + a demo main
                        that calls it with the first example's arguments

The demo is generated by matching the function parameters against the variable
names in the official example, so it only exists where it can be built safely —
problems we cannot parse simply ship without a runnable demo.

    python3 site/leetcode/build_bank_json.py
"""
from __future__ import annotations

import ast
import importlib.util
import json
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
SITE = HERE.parent
OUT = SITE / "leetcode" / "problems.json"

C_TYPES = {
    "int": lambda v: str(int(v)),
    "long": lambda v: str(int(v)),
    "unsigned": lambda v: str(int(v)),
    "long long": lambda v: f"{int(v)}LL",
    "short": lambda v: str(int(v)),
    "double": lambda v: f"{float(v)}",
    "float": lambda v: f"{float(v)}",
    "bool": lambda v: "true" if v else "false",
    "char": lambda v: "'" + str(v).replace("'", "\\'") + "'",
    "string": lambda v: '"' + str(v).replace("\\", "\\\\").replace('"', '\\"') + '"',
}

JAVA_TYPES = {
    "int": lambda v: str(int(v)),
    "long": lambda v: f"{int(v)}L",
    "short": lambda v: f"(short){int(v)}",
    "double": lambda v: f"{float(v)}",
    "float": lambda v: f"{float(v)}f",
    "boolean": lambda v: "true" if v else "false",
    "char": lambda v: "'" + str(v).replace("'", "\\'") + "'",
    "String": lambda v: '"' + str(v).replace("\\", "\\\\").replace('"', '\\"') + '"',
}

ARRAY_TYPES = {
    "int": "int", "long": "long", "short": "int", "double": "double",
    "float": "double", "boolean": "boolean", "char": "char", "String": "String",
}


# --------------------------------------------------------------------------- #
#  example parsing
# --------------------------------------------------------------------------- #
def parse_example_values(text: str) -> dict | None:
    """`nums = [1,2,3], k = 2` → {"nums": [1,2,3], "k": 2}  (None if unparseable)."""
    text = text.strip()
    if "=" not in text:
        return None
    values: dict[str, object] = {}
    # split on top-level commas
    parts, depth, quote, buf = [], 0, None, ""
    for ch in text:
        if quote:
            buf += ch
            if ch == quote:
                quote = None
            continue
        if ch in "\"'":
            quote = ch
            buf += ch
        elif ch in "[{(":
            depth += 1
            buf += ch
        elif ch in "]})":
            depth -= 1
            buf += ch
        elif ch == "," and depth == 0:
            parts.append(buf)
            buf = ""
        else:
            buf += ch
    parts.append(buf)
    for part in parts:
        if "=" not in part:
            return None
        name, _, raw = part.partition("=")
        name, raw = name.strip(), raw.strip()
        try:
            values[name] = ast.literal_eval(raw)
        except (ValueError, SyntaxError):
            try:
                values[name] = ast.literal_eval(str(int(raw)))         # plain numbers
            except (ValueError, SyntaxError):
                return None
    return values or None


# --------------------------------------------------------------------------- #
#  C++ demos
# --------------------------------------------------------------------------- #
def cpp_literal(type_name: str, value) -> str | None:
    t = " ".join(type_name.replace("&", " ").replace("*", " ").split())
    t = re.sub(r"\bconst\b", "", t).strip()
    if t.startswith("vector<") and t.endswith(">"):
        inner = t[len("vector<"):-1].strip()
        return cpp_vector_literal(inner, value)          # recurse element-wise
    if t in C_TYPES:
        try:
            return C_TYPES[t](value)
        except (TypeError, ValueError):
            return None
    if t.startswith("pair<") and t.endswith(">"):
        inner = t[len("pair<"):-1]
        split = [x.strip() for x in split_top(inner)]
        if len(split) == 2 and isinstance(value, (list, tuple)) and len(value) == 2:
            a, b = cpp_literal(split[0], value[0]), cpp_literal(split[1], value[1])
            if a and b:
                return "{" + a + ", " + b + "}"
    return None


def cpp_vector_literal(inner: str, values) -> str | None:
    if not isinstance(values, (list, tuple)):
        return None
    items = []
    for v in values:
        lit = cpp_literal(inner, v)
        if lit is None:
            return None
        items.append(lit)
    return "{" + ", ".join(items) + "}"


def split_top(text: str, sep: str = ",") -> list[str]:
    parts, depth, buf = [], 0, ""
    for ch in text:
        if ch in "<([{":
            depth += 1
            buf += ch
        elif ch in ">)]}":
            depth -= 1
            buf += ch
        elif ch == sep and depth == 0:
            parts.append(buf)
            buf = ""
        else:
            buf += ch
    parts.append(buf)
    return [p for p in parts if p.strip()]


def cpp_demo(code: str, example: str) -> str | None:
    if NODE_MARKERS.search(code) or JUDGE_APIS.search(code):
        return None
    values = parse_example_values(example)
    if not values:
        return None
    src = strip_comments(code)
    m = re.search(r"^([A-Za-z_][\w:<>,\s\*&\[\]]*?)\s+(\w+)\s*\(([^;{]*)\)\s*\{", src, re.M)
    if not m:
        return None
    ret, name, params = m.group(1).strip(), m.group(2), m.group(3)
    if name in ("main",) or "Solution" in ret:
        return None
    args, decls, exprs = [], [], []
    for raw in split_top(params):
        bits = raw.strip().replace("const ", "").replace("&", "").strip()
        pieces = bits.split()
        if len(pieces) < 2:
            return None
        pname = pieces[-1].strip()
        ptype = " ".join(pieces[:-1])
        if pname not in values:
            return None
        value = values[pname]
        if ptype.startswith("vector<"):
            inner = ptype[len("vector<"):-1]
            lit = cpp_vector_literal(inner, value)
        else:
            lit = cpp_literal(ptype, value)
        if lit is None:
            return None
        decls.append(f"    {ptype} {pname} = {lit};")
        exprs.append(pname)
    printer = ""
    call = f"{name}({', '.join(exprs)})"
    ret_clean = re.sub(r"\b(static|inline)\b", "", ret).strip()
    if ret_clean == "void":
        body = f"    {call};"
    else:
        if "vector<" in ret_clean:
            printer = CPP_PRINTER
            body = f"    __pr({call});\n    cout << endl;"
        elif ret_clean in ("bool",):
            printer = CPP_PRINTER
            body = f"    __pr({call});\n    cout << endl;"
        elif ret_clean in ("string", "char"):
            printer = CPP_PRINTER
            body = f"    __pr({call});\n    cout << endl;"
        else:
            body = f"    cout << {call} << endl;"
    return ("\n\n" + printer + "\nint main() {\n" + "\n".join(decls) + "\n" + body + "\n    return 0;\n}\n").lstrip("\n")


CPP_PRINTER = """// --- demo printer -------------------------------------------------------
void __pr(long long x) { cout << x; }
void __pr(int x) { cout << x; }
void __pr(unsigned x) { cout << x; }
void __pr(double x) { cout << x; }
void __pr(bool x) { cout << (x ? "true" : "false"); }
void __pr(char x) { cout << '\\'' << x << '\\''; }
void __pr(const string& x) { cout << '"' << x << '"'; }
template <class T> void __pr(const vector<T>& v) {
    cout << '[';
    for (size_t i = 0; i < v.size(); i++) { if (i) cout << ','; __pr(v[i]); }
    cout << ']';
}
"""


# --------------------------------------------------------------------------- #
#  Java demos
# --------------------------------------------------------------------------- #
def java_literal(type_name: str, value) -> str | None:
    t = type_name.strip()
    if t.endswith("[][]"):
        base = t[:-4]
        if base not in ARRAY_TYPES or not isinstance(value, (list, tuple)):
            return None
        rows = []
        for row in value:
            lit = java_literal(base + "[]", row)
            if lit is None:
                return None
            rows.append(lit)
        return "new " + base + "[][]{" + ", ".join(rows) + "}"
    if t.endswith("[]"):
        base = t[:-2]
        if base not in ARRAY_TYPES or not isinstance(value, (list, tuple)):
            return None
        fn = JAVA_TYPES[base]
        items = []
        for v in value:
            try:
                items.append(fn(v))
            except (TypeError, ValueError):
                return None
        return "new " + base + "[]{" + ", ".join(items) + "}"
    if t in JAVA_TYPES:
        try:
            return JAVA_TYPES[t](value)
        except (TypeError, ValueError):
            return None
    return None


def java_demo(code: str, example: str) -> tuple[str, str] | None:
    """Returns (class-name, body of main) or None."""
    if NODE_MARKERS.search(code) or JUDGE_APIS.search(code):
        return None
    values = parse_example_values(example)
    if not values:
        return None
    src = strip_comments(code, java=True)
    m = re.search(r"(?:public\s+|private\s+|protected\s+)?(?:static\s+)?"
                  r"([A-Za-z_][\w<>\[\],\s]*?)\s+(\w+)\s*\(([^)]*)\)\s*\{", src)
    if not m:
        return None
    ret, name, params = m.group(1).strip(), m.group(2), m.group(3)
    if name in ("main",) or name in ("Solution",):
        return None
    if ret in ("class", "interface", "void") and name[0].islower() and ret == "void":
        pass
    decls, exprs = [], []
    for raw in split_top(params):
        bits = raw.strip().replace("final ", "").strip()
        pieces = bits.split()
        if len(pieces) < 2:
            return None
        pname = pieces[-1]
        ptype = " ".join(pieces[:-1])
        if pname not in values:
            return None
        lit = java_literal(ptype, values[pname])
        if lit is None:
            return None
        decls.append(f"        {ptype} {pname} = {lit};")
        exprs.append(pname)
    call = f"new Main().{name}({', '.join(exprs)})"
    if ret == "void":
        body = [f"        {call};"]
    elif ret.endswith("[][]"):
        body = [f"        System.out.println(java.util.Arrays.deepToString({call}));"]
    elif ret.endswith("[]"):
        base = ret[:-2]
        printer = "toString" if base in ("int", "long", "short", "double", "float",
                                        "boolean", "char", "byte") else "deepToString"
        body = [f"        System.out.println(java.util.Arrays.{printer}({call}));"]
    elif ret == "boolean":
        body = [f"        System.out.println({call});"]
    elif ret in ("char", "String"):
        body = [f"        System.out.println({call});"]
    else:
        body = [f"        System.out.println({call});"]
    return ("Main", decls + body)


