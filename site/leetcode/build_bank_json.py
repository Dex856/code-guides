def java_literal(type_name: str, value) -> str | None:
    t = type_name.strip()
    if t.endswith("[][]"):
        base = t[:-4]
        if base not in ARRAY_TYPES or not isinstance(value, (list, tuple)):
            return None
        rows = []
        for row in value:
            lit = java_literal(base + "[]", row)
            if lit is None:
                return None
            rows.append(lit)
        return "new " + base + "[][]{" + ", ".join(rows) + "}"
    if t.endswith("[]"):
        base = t[:-2]
        if base not in ARRAY_TYPES or not isinstance(value, (list, tuple)):
            return None
        fn = JAVA_TYPES[base]
        items = []
        for v in value:
            try:
                items.append(fn(v))
            except (TypeError, ValueError):
                return None
        return "new " + base + "[]{" + ", ".join(items) + "}"
    if t in JAVA_TYPES:
        try:
            return JAVA_TYPES[t](value)
        except (TypeError, ValueError):
            return None
    return None


def java_demo(code: str, example: str) -> tuple[str, str] | None:
    """Returns (class-name, body of main) or None."""
    if NODE_MARKERS.search(code) or JUDGE_APIS.search(code):
        return None
    values = parse_example_values(example)
    if not values:
        return None
    src = strip_comments(code, java=True)
    m = re.search(r"(?:public\s+|private\s+|protected\s+)?(?:static\s+)?"
                  r"([A-Za-z_][\w<>\[\],\s]*?)\s+(\w+)\s*\(([^)]*)\)\s*\{", src)
    if not m:
        return None
    ret, name, params = m.group(1).strip(), m.group(2), m.group(3)
    if name in ("main",) or name in ("Solution",):
        return None
    if ret in ("class", "interface", "void") and name[0].islower() and ret == "void":
        pass
    decls, exprs = [], []
    for raw in split_top(params):
        bits = raw.strip().replace("final ", "").strip()
        pieces = bits.split()
        if len(pieces) < 2:
            return None
        pname = pieces[-1]
        ptype = " ".join(pieces[:-1])
        if pname not in values:
            return None
        lit = java_literal(ptype, values[pname])
        if lit is None:
            return None
        decls.append(f"        {ptype} {pname} = {lit};")
        exprs.append(pname)
    call = f"new Main().{name}({', '.join(exprs)})"
    if ret == "void":
        body = [f"        {call};"]
    elif ret.endswith("[][]"):
        body = [f"        System.out.println(java.util.Arrays.deepToString({call}));"]
    elif ret.endswith("[]"):
        base = ret[:-2]
        printer = "toString" if base in ("int", "long", "short", "double", "float",
                                        "boolean", "char", "byte") else "deepToString"
        body = [f"        System.out.println(java.util.Arrays.{printer}({call}));"]
    elif ret == "boolean":
        body = [f"        System.out.println({call});"]
    elif ret in ("char", "String"):
        body = [f"        System.out.println({call});"]
    else:
        body = [f"        System.out.println({call});"]
    return ("Main", decls + body)


