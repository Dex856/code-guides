PY_IMPORTS = [
    (r"\b(bisect_left|bisect_right|bisect)\b", "from bisect import bisect_left, bisect_right, bisect"),
    (r"\b(defaultdict|deque|Counter|OrderedDict)\b",
     "from collections import defaultdict, deque, Counter, OrderedDict"),
    (r"\b(heappush|heappop|heapify|nlargest|nsmallest|heapreplace|heappushpop)\b", "import heapq"),
    (r"\b(lru_cache|cache|reduce)\b", "from functools import lru_cache, cache, reduce"),
    (r"\b(combinations|permutations|product|combinations_with_replacement)\b", "from itertools import combinations, permutations, product"),
    (r"\b(accumulate|groupby)\b", "from itertools import accumulate, groupby"),
    (r"\b(isqrt|floor|ceil|gcd|comb|factorial|perm)\b", "from math import isqrt, floor, ceil, gcd, comb, factorial, perm"),
    (r"\b(inf|log|sqrt|log2|pow)\b", "import math"),
    (r"\bre\.", "import re"),
    (r"\bint\(.*, *16\)", "import sys"),
]


def python_prelude(code: str) -> str:
    """The bank snippets rely on the judge's namespace for a few helpers; a real
    interpreter needs the imports written out."""
    needed = []
    for pattern, line in PY_IMPORTS:
        if re.search(pattern, code):
            module = line.split()[1].split(".")[0] if line.startswith("from") else line.split()[1]
            if re.search(r"^\s*(?:from\s+" + module + r"\s+import|import\s+" + module + r"\b)", code, re.M):
                continue
            needed.append(line)
    return "\n".join(needed) + ("\n\n" if needed else "")

NODE_MARKERS = re.compile(r"\b(TreeNode|ListNode|Node|TreeLinkNode)\b")
# APIs the judge provides (declared in a snippet but never defined) — a demo
# program cannot link or run against them, so those problems ship without one.
JUDGE_APIS = re.compile(r"\b(isBadVersion|is_bad_version|guess|MountainArray|read4|Reader4|NestedInteger|ArrayReader|Master|Sea)\b")


def python_demo(code: str, example: str, other_langs: str = "") -> str | None:
    # The example is a serialised tree / linked list / graph when any language's
    # solution mentions a node type — a Python signature alone cannot show that.
    if NODE_MARKERS.search(code) or NODE_MARKERS.search(other_langs) or JUDGE_APIS.search(code):
        return None
    values = parse_example_values(example)
    if not values:
        return None
    src = strip_comments(code, python=True)
    m = re.search(r"^def\s+(\w+)\s*\(([^)]*)\)\s*:", src, re.M)
    if not m:
        return None
    name, params = m.group(1), m.group(2)
    args = []
    for raw in split_top(params):
        arg = raw.strip().split(":")[0].split("=")[0].strip()
        if arg in ("self", "cls") or not arg:
            if arg in ("self", "cls"):
                return None
            continue
        if arg not in values:
            return None
        args.append(repr(values[arg]))
    return (f"_result = {name}({', '.join(args)})\n"
            f"if _result is not None:\n"
            f"    print(_result)")


# --------------------------------------------------------------------------- #
#  helpers
# --------------------------------------------------------------------------- #
def strip_comments(code: str, java: bool = False, python: bool = False) -> str:
    code = re.sub(r"/\*.*?\*/", "", code, flags=re.S)
    if python:
        return "".join(line.split("#")[0] + "\n" for line in code.splitlines())
    code = re.sub(r"//[^\n]*", "", code)
    return code


def first_python_signature(code: str) -> str | None:
    for line in code.splitlines():
        line = line.strip()
        if line.startswith("def "):
            return line.rstrip(":")
    return None


PY_STARTER = '''import sys

def solve():
    data = sys.stdin.read().split()
    # TODO: read the input the way the problem describes, then print the answer
    print(0)

if __name__ == "__main__":
    solve()
'''

CPP_STARTER = '''int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    // TODO: read the input, compute, print the answer
    cout << 0 << '\\n';
    return 0;
}
'''

JAVA_STARTER = '''public class Main {
    public static void main(String[] args) {
        Scanner sc = new Scanner(System.in);

        // TODO: read the input, compute, print the answer
        System.out.println(0);
    }
}
'''


def python_starter(solution: str) -> str:
    sig = first_python_signature(solution)
    if not sig:
        return PY_STARTER
    body = f"""
{sig}:
    # TODO: implement
    pass


if __name__ == "__main__":
    # Example: turn the first sample into a call and print the result.
    print(solve())
"""
    return body.lstrip("\n")


def java_starter(solution: str) -> str:
    src = strip_comments(solution, java=True)
    m = re.search(r"^[\t ]*(?:public\s+|private\s+|protected\s+)?(?:static\s+)?"
                  r"([A-Za-z_][\w<>\[\],\s]*?)\s+(\w+)\s*\(([^)]*)\)\s*\{", src, re.M)
    if not m:
        return JAVA_STARTER
    ret, name, params = m.group(1).strip(), m.group(2), m.group(3)
    return (f"public class Main {{\n"
            f"    // {ret} {name}({params}) — implement this\n"
            f"    {'static ' if 'static' in solution[:m.start()] else ''}{ret} {name}({params}) {{\n"
            f"        // TODO\n"
            f"        return {'null' if not ret.islower() or ret in ('int', 'long', 'short', 'double', 'float') else 'false'};\n"
            f"    }}\n"
            f"}}\n")


def cpp_starter(solution: str) -> str:
    src = strip_comments(solution)
    m = re.search(r"^([A-Za-z_][\w:<>,\s\*&\[\]]*?)\s+(\w+)\s*\(([^;{]*)\)\s*\{", src, re.M)
    if not m:
        return CPP_STARTER
    ret, name, params = m.group(1).strip(), m.group(2), m.group(3)
    return (f"{ret} {name}({params}) {{\n"
            f"    // TODO\n"
            f"    return {ret.rstrip('&')}{{}};\n"
            f"}}\n\n"
            f"int main() {{\n"
            f"    // call {name}(...) with the sample arguments and print the result\n"
            f"    return 0;\n"
            f"}}\n")


# --------------------------------------------------------------------------- #
#  main
# --------------------------------------------------------------------------- #
def main() -> int:
    banks = []
    for path in sorted(HERE.glob("bank_*.py")):
        spec = importlib.util.spec_from_file_location(path.stem, path)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)              # type: ignore[union-attr]
        banks.append({"topic": mod.TOPIC, "problems": mod.PROBLEMS})

    topics, problems = [], []
    stats = {"total": 0, "demo_py": 0, "demo_cpp": 0, "demo_java": 0}
    for ti, bank in enumerate(banks, 1):
        topics.append({"n": ti, "name": bank["topic"]["name"], "tagline": bank["topic"]["tagline"]})
        for prob in bank["problems"]:
            stats["total"] += 1
            example = prob["examples"][0][0] if prob.get("examples") else ""
            entry = {
                "slug": prob["slug"], "title": prob["title"], "difficulty": prob["difficulty"],
                "topic_n": ti, "topic": bank["topic"]["name"], "pattern": prob["pattern"],
                "statement": prob["statement"], "examples": prob.get("examples", []),
                "constraints": prob.get("constraints", []), "approach": prob["approach"],
                "complexity": list(prob["complexity"]),
                "code": {k: prob["code"][k] for k in ("cpp", "java", "python")},
                "starter": {}, "solution_run": {},
            }
            # ---- python
            demo = python_demo(prob["code"]["python"], example,
                               prob["code"]["cpp"] + prob["code"]["java"])
            entry["starter"]["python"] = python_starter(prob["code"]["python"])
            if demo:
                body = prob["code"]["python"].rstrip()
                entry["solution_run"]["python"] = python_prelude(body) + body + "\n\n" + demo + "\n"
                stats["demo_py"] += 1
            # ---- c++
            demo_cpp = cpp_demo(prob["code"]["cpp"], example)
            entry["starter"]["cpp"] = cpp_starter(prob["code"]["cpp"])
            if demo_cpp:
                entry["solution_run"]["cpp"] = prob["code"]["cpp"].rstrip() + "\n\n" + demo_cpp
                stats["demo_cpp"] += 1
            # ---- java
            demo_java = java_demo(prob["code"]["java"], example)
            entry["starter"]["java"] = java_starter(prob["code"]["java"])
            if demo_java:
                _, body = demo_java
                entry["solution_run"]["java"] = ("import java.util.*;\n\n"
                                                 "public class Main {\n"
                                                 + prob["code"]["java"].rstrip() + "\n\n"
                                                 "    public static void main(String[] args) {\n"
                                                 + "\n".join(body) + "\n"
                                                 "    }\n}\n")
                stats["demo_java"] += 1
            problems.append(entry)

    payload = {"count": len(problems), "topics": topics, "problems": problems,
               "demos": {"python": stats["demo_py"], "cpp": stats["demo_cpp"], "java": stats["demo_java"]}}
    OUT.write_text(json.dumps(payload, separators=(",", ":"), ensure_ascii=False))
    print(f"wrote {OUT.relative_to(SITE.parent)}  ({OUT.stat().st_size/1024/1024:.2f} MB)")
    print(f"  problems: {stats['total']}")
    print(f"  runnable demos: python {stats['demo_py']}/{stats['total']}"
          f" · c++ {stats['demo_cpp']}/{stats['total']} · java {stats['demo_java']}/{stats['total']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
