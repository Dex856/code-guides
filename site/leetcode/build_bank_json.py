def parse_example_values(text: str) -> dict | None:
    """`nums = [1,2,3], k = 2` → {"nums": [1,2,3], "k": 2}  (None if unparseable)."""
    text = text.strip()
    if "=" not in text:
        return None
    values: dict[str, object] = {}
    # split on top-level commas
    parts, depth, quote, buf = [], 0, None, ""
    for ch in text:
        if quote:
            buf += ch
            if ch == quote:
                quote = None
            continue
        if ch in "\"'":
            quote = ch
            buf += ch
        elif ch in "[{(":
            depth += 1
            buf += ch
        elif ch in "]})":
            depth -= 1
            buf += ch
        elif ch == "," and depth == 0:
            parts.append(buf)
            buf = ""
        else:
            buf += ch
    parts.append(buf)
    for part in parts:
        if "=" not in part:
            return None
        name, _, raw = part.partition("=")
        name, raw = name.strip(), raw.strip()
        try:
            values[name] = ast.literal_eval(raw)
        except (ValueError, SyntaxError):
            try:
                values[name] = ast.literal_eval(str(int(raw)))         # plain numbers
            except (ValueError, SyntaxError):
                return None
    return values or None


