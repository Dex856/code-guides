def python_starter(solution: str) -> str:
    sig = first_python_signature(solution)
    if not sig:
        return PY_STARTER
    body = f"""
{sig}:
    # TODO: implement
    pass


if __name__ == "__main__":
    # Example: turn the first sample into a call and print the result.
    print(solve())
"""
    return body.lstrip("\n")


